-- ============================================================
-- ② 索引还原 —— 逐字还原 0002_foundation.up.sql:73 的定义
-- ============================================================
--
-- 逐字还原（而不是「写一条等价的」）是硬要求：否则「回滚之后再灌一次全部 up」
-- 会得到一个与直接灌一遍不同的库，而这正是 CI 的正反向验证唯一能盯住的那件事。
--
-- ------------------------------------------------------------
-- 🔴 这一步在生产上**可能失败，且失败是正确行为**
-- ------------------------------------------------------------
--
-- up 之后，库里合法地允许出现「同一邮箱：一条 disabled + 一条在职」——
-- **那正是 up 存在的全部理由**（离职再入职）。只要现实中真的发生过一次，
-- 这条 `CREATE UNIQUE INDEX`（无 WHERE）就会撞上重复值而失败。
--
-- ⚠️ 这是「**加约束容易、去约束难**」的一般情形，写在这里当作下一次放宽约束时的参照：
--    约束一旦放宽，数据就会走进新放开的那片区域；再想收回来，**先得决定那些数据怎么办**。
--    而「怎么办」在这里是一次真正的人工决策 —— 改掉其中一个邮箱？把旧行硬删（会打断
--    audit_logs 的指认，见 admin_accounts.sql §2.4）？还是干脆不回滚？
--    **一支 migration 不该替人做这个决定**，所以这里不加任何「自动清理重复项」的补救。
--    （同一条纪律的另外两个实例：0015.down 的 char(3) 窄化、0018.down 的科目删除。）
--
-- ⚠️ 也就是说 up 与 down 在这一句上**不对称**：up 方向永远不会因数据失败
--    （新条件比旧条件宽），down 方向会。deploy.md §12.3 那句「schema 是整条流水线里
--    唯一不可回滚的一步」在这里有一个具体形状。
--
-- CI 的空库上碰不到这一条：migrate-verify 与 CI 的 migrations 作业从不写一行 admin_users。
-- 也就是说**这条失败路径永远不会被自动化验证到**，它只会在真实数据上第一次出现。
--
-- 事务包裹的理由与 up 相同，而在 down 方向更重要：这一句**本来就可能失败**，
-- 不包事务的话失败之后库里是「一条索引都没有」；包了事务，失败之后留下的是
-- up 的那条部分索引 —— 一个仍然自洽、仍然在保护数据的状态。
BEGIN;
DROP INDEX admin_users_email_uk;
CREATE UNIQUE INDEX admin_users_email_uk ON admin_users (lower(email));
COMMIT;


