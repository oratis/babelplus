-- 0017 · subscription_fetch_log.cn_mode（ADR 0015 §4.9 / §5.7）
--
-- 事实源：ADR 0015 §5.7（列定义、口径与分母）、§2.3 反方第 1 条（推翻「本 ADR 不改 schema」）。
--
-- ============================================================
-- 为什么加这一列
-- ============================================================
--
-- ADR 0015 给国内直连白名单配了一条失效条件：**`?cn=proxy` 的使用率 > 20% ⇒ 白名单本身错了，
-- 整体回退而不是继续打补丁**。而 `subscription_fetch_log` 的 DDL（0008）**没有任何一列能记 `cn` 参数** ——
-- 于是那条失效条件收集不到数据，是一条**做了等于没做**的失效条件。
--
-- 按本项目 AGENTS.md §3 的事实纪律：**一条从未被验证过的检查应默认视为不工作。**
-- 一条永远无法被触发的失效条件比没有失效条件更坏 —— 它让人以为有刹车。
-- 草稿写着「本 ADR 不改 schema」，那是一个**选择**，不是约束；ADR 0015 推翻了它，本文件是落点。
--
-- ============================================================
-- 为什么是一列裸 text，没有 CHECK、没有回填、没有 NOT NULL
-- ============================================================
--
-- 与同表的 `format` / `client_flag` **同规格**（0008 原文里那两列也是可空裸 text）。逐条：
--  · 可空：历史行为 NULL。这张表是 90 天硬删的日志表，回填一个假的 'direct' 只会污染分母 ——
--    NULL 与 'direct' 在语义上不同，前者是「那时还没有这个开关」，后者是「用户当时选了直连」。
--  · 无 CHECK：这是**观测列**不是**状态列**。将来加第三种 cn 模式时，
--    一条 CHECK 会让「记录一次我们还不认识的取值」变成一次 500 ——
--    而记录不认识的取值恰恰是观测列该做的事。取值合法性在 handler 侧归一化。
--  · 无 NOT NULL / 无 DEFAULT：可加性迁移，不重写全表。`subscription_fetch_log` 是订阅路径上
--    每次拉取都写一行的表（节点/客户端每几小时一次 × 全部用户），全表重写要锁住整条订阅下发路径。
ALTER TABLE subscription_fetch_log ADD COLUMN cn_mode text;

COMMENT ON COLUMN subscription_fetch_log.cn_mode IS
  '本次订阅拉取的国内分流模式：''direct''（缺省 / ?cn=direct，下发国内直连白名单）
   / ''proxy''（?cn=proxy，不下发任何 cnDirect* 规则，回到全局代理）；NULL = 该列存在之前的历史行。
   🔴 分母按**人**不按次（两者差 5 倍，ADR 0015 §5.7 明确）：
     count(DISTINCT user_id) FILTER (WHERE cn_mode = ''proxy'') / NULLIF(count(DISTINCT user_id), 0)
     FROM subscription_fetch_log WHERE request_at > now() - interval ''7 days''
   > 20% ⇒ 白名单本身错了，整体回退而不是继续打补丁（ADR 0015 §5.7 的失效条件）。';

-- 刻意不建索引：这条统计是 7 天窗口的按人去重聚合，跑在既有的
-- `subscription_fetch_log_at_idx (request_at)` 上就够（该列本来就是 90 天硬删用的）。
-- 为一条每周看一次的运营指标再建一条索引，成本落在每次订阅拉取的写路径上 —— 不划算。
