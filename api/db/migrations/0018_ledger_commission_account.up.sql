-- 0018 · 补一个科目：expense:commission（佣金划转的借方腿）
--
-- 事实源：ADR 0013 §3.5（佣金的记账与追回）、ADR 0012 §17.6(c)（0015 seed 的那张科目表）、
--         0007_ledger.up.sql（ledger_accounts 的 DDL 与「SUM(lines.amount) = 0」不变量）、
--         api/db/queries/wallet.sql §5（GetCommissionTransferAccounts，已把这个缺口写成「提前失败」）。
--
-- ============================================================
-- 为什么 0015 的 seed 里没有它（不是遗漏，是两份 ADR 的边界）
-- ============================================================
--
-- 0015 的科目 seed **逐字照抄 ADR 0012 §17.6(c) 的科目表**，而 §17.6 通篇只处理一件事：
-- **收款链路**（链上收款、跨币种桥接、写销、汇率缓冲、D6 人工核对）。
-- 佣金既不是收款也不是跨币种，它整个属于 **ADR 0013 §3.5** —— 一份**独立的**裁决。
--
-- 两份 ADR 是同一批合并的，但 seed 只跟了前一份。
-- 于是「科目表已经建好了」这句话在两份 ADR 的交界处是假的，而**没有任何东西会说出来**：
-- 0015 自己是完整的（它覆盖了它声称覆盖的那一节），0013 没有对应的迁移落点，
-- CI 的建表数断言只数表不数行。缺口从头到尾没有一个报错的地方。
--
-- ⚠️ 记录一条推论，供下一次改科目表的人用：
--    **科目 seed 的正确边界是「有分录腿指向它的全部 code」，不是「某一节 ADR 的表格」。**
--    按 ADR 分节抄表，缺的永远是跨节的那几个。
--
-- ============================================================
-- 缺它的现象：不是启动失败，是用户点「划转佣金」时 500
-- ============================================================
--
-- 划转的贷方腿是 `liability:user_wallet`（0015 有），借方腿必须是「我们为拉新付出的成本」。
-- 借方腿取不到科目 id，这条分录就写不出来，而 0007 的核心不变量是
-- `∀ entry: SUM(lines.amount) = 0`（ADR 0012 §17.6(a) 修订为 per `(entry_id, currency)`）——
-- 只写贷方那一条腿的话，账当天就不平，FindUnbalancedLedgerEntries 每天报红。
--
-- 🔴 失败点在**用户已经点过按钮之后**：
--    服务启动不会失败（没有任何东西在启动时校验科目表），
--    面板打开不会失败（listCommissions 根本不读 ledger_accounts），
--    只有 POST /api/v1/invites/transfer 会失败 —— 而且是对着一个**看得见自己有多少佣金**
--    的用户失败。他会重试，每次都 500，然后开工单。
--    实测：`GetCommissionTransferAccounts` 的 `expense_account_id` 返回 NULL
--    （那条查询是 `max(id) FILTER (WHERE code = 'expense:commission')` 的聚合，恒返回一行，
--     所以缺科目表现为 NULL 而不是 0 行 —— 这也是它被写成「提前失败」的原因：
--     在动 commissions.status、动 wallet_balances 之前先判 nil，绝不写半条分录）。
--
-- ============================================================
-- 为什么是一个新科目，而不是复用 expense:refund
-- ============================================================
--
-- ADR 0013 §3.5 第 2 步把 `expense:refund` 的用途**写死**了：只用于 `destination='original'`
-- 的退款，以及第 4 步追不回来的佣金（那记的是真实损失）。§3.5 的原话是
-- destination='balance' 的分录「绝不允许碰 expense:refund」，理由是
-- 「损益表上会凭空出现一笔从未发生的费用」。
--
-- 把佣金划转记在它下面会犯同一类错误、方向相反：**获客成本与退款损失混成一个数**。
-- 那两个数的用途完全不同 —— 前者除以新增用户数是 CAC，是决定要不要继续做返佣的依据；
-- 后者是需要解释的异常。混在一起之后，返佣做得越好这个数字越难看，
-- 而且**没有任何办法事后拆开**（ledger_lines 上没有第二个维度可以区分它们）。
--
-- 币种取 CNY：佣金全程以人民币分计价（commissions.amount 是分，
-- 贷方腿 liability:user_wallet 也是 CNY）。两条腿必须同币种，否则按
-- (entry_id, currency) 分组之后各自不平 —— 那正是 ADR 0012 §17.6(a) 修订不变量要防的形态。

-- 幂等：`ledger_accounts.code` 上有 UNIQUE（0007:16），重放走 DO NOTHING。
-- 🔴 幂等是硬要求而不是礼貌：生产上这支迁移可能与 0015 的 seed 在同一个库上先后跑过
--    （谁先补上这一行都算数），而一支会在重放时炸的 seed 迁移，
--    会把「多跑了一次」变成一次需要人工介入的部署失败。
INSERT INTO ledger_accounts (code, kind, currency) VALUES
  ('expense:commission', 'expense', 'CNY')
ON CONFLICT (code) DO NOTHING;
