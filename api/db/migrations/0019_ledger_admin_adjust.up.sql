-- ============================================================
-- ① expense:admin_adjust —— D10「调整用户余额」的借方腿
-- ============================================================
--
-- ------------------------------------------------------------
-- 为什么前面三支碰过科目表的迁移都没有它（不是遗漏，是三条边界都不覆盖它）
-- ------------------------------------------------------------
--
--  · 0015 的 10 条 seed **逐字照抄 ADR 0012 §17.6(c) 的科目表**，而 §17.6 通篇只处理
--    **收款链路**：链上收款、跨币种桥接、写销、汇率缓冲、D6 人工核对。
--  · 0018 补的 expense:commission 属于 **ADR 0013 §3.5** —— 佣金，即获客成本。
--  · 而**管理员手工调余额不属于任何一份已有裁决**。它不是业务流程，是**运维动作**：
--    线下现金、补偿、误操作的更正、代付。ADR 0012 §16.1 亲手把它从 D6 里分出去
--    （「真正没有 txid 的手工入账不走 D6，走 D10 调整余额——两条路径的职责因此彻底分开」），
--    然后 §23 把它的记账形态**明确留在外面**：
--       「『付款人不必自持 U』的入金路径的记账形态 —— 失效条件 1 只指出零件都在
--         （wallet_topup / method: balance / AdjustAdminUserBalance），没有设计代付人之间的
--         结算与凭证。**它会牵动 §17.6 的科目表，应当单独成文。**」
--
--    也就是说：这个缺口不是没人想到，是被**有意推迟**的。而冻结契约里
--    `POST /admin/users/{id}/balance-adjust` 已经存在（api-contract §1262 模块 14）。
--    **端点先于裁决落了地，缺口就掉在两者之间** —— 这一类缺口没有任何编译期或启动期的东西会说出来。
--
-- 🔴 **本文件只补一个科目，不当作 §23 那条未决项的答案。** 补科目解决的是
--    「D10 写不出借贷平衡的分录」这一个具体故障；§23 要的是**代付人之间的结算与凭证**，
--    那需要一个「谁替谁付了多少」的维度，而 ledger_lines 上除了 subject_id 没有第二个维度
--    （0007:37 只有一列）。那件事仍然需要一份裁决 + 另一支迁移。
--    **不要因为本行存在就以为代付路径已经设计过了。**
--
-- ------------------------------------------------------------
-- 缺它的现象：不是启动失败，是管理员点「调整余额」时拿到 503
-- ------------------------------------------------------------
--
-- 服务启动不会失败（没有任何东西在启动时校验科目表），管理面打开不会失败
-- （用户详情页的余额读的是 wallet_balances 缓存，根本不碰 ledger_accounts）。
-- 唯一的暴露点是 `POST /admin/users/{id}/balance-adjust` ——
-- 而那已经是管理员**填完 L2 reason、按完 L3 TOTP、点掉 L1 确认串之后**的那一刻。
--
-- 实测（0001–0018 灌完的空库）：`GetAdminBalanceAdjustAccounts` 返回
-- `adjust_account_id = NULL`。它是 `max(id) FILTER (WHERE code = …)` 的聚合，**恒返回一行**，
-- 所以缺科目表现为 NULL 而不是 0 行 —— 这也正是那条查询被写成「提前失败闸」的原因：
-- 在动 ledger_entries、动 wallet_balances 之前先判 nil，**绝不写半条腿**。
--
-- ⚠️ 那里返 **503 而不是 500** 是刻意的，理由在人的行为上：500 是「出错了，再试一次」，
--    管理员会重试，而 D10 的每一次尝试都要重新过一遍 TOTP —— 审计里会留下一串
--    看起来像有人在反复试探调余额的记录，而真正的原因只是少了一行 seed。
--    503 是「这台机器现在做不了这件事」，语义正确，且能把人引向部署而不是引向重试。
--
-- ------------------------------------------------------------
-- 为什么是新科目，而不是复用现有 11 个里的任何一个（逐条排除）
-- ------------------------------------------------------------
--
--  · `asset:manual_reconcile` —— **决定性的一条**。它是 D6 专用（ADR 0012 §16.2），
--    而它的价值全部来自一个性质：**余额长期非零 = 有人标了「已支付」但钱没进来**。
--    这是「全系统最大的内部欺诈面」唯一的一盏指示灯。把 D10 的调整混进这个科目，
--    这盏灯就会因为正常的运维动作而长期亮着 —— 等于把报警关掉，而且是以「复用了现成科目」
--    这种看起来很节俭的方式关掉的。
--  · `expense:refund` —— 用途被 ADR 0013 §3.5 第 2 步**写死**：只用于 destination='original'
--    的退款，以及第 4 步追不回来的佣金（那记的是真实损失）。§3.5 的原话是
--    destination='balance' 的分录「绝不允许碰 expense:refund」，理由是
--    「损益表上会凭空出现一笔从未发生的费用」。管理员调账记在它下面犯的是同一类错误。
--  · `expense:commission` —— 0018 刚建的**获客成本**。它除以新增用户数就是 CAC，
--    是决定要不要继续做返佣的依据。混进管理员调账之后这个数字不再是 CAC，
--    而且**事后拆不开**（同上：ledger_lines 上没有第二个维度能区分它们）。
--  · `liability:user_wallet` —— 它是本条分录的**另一条腿**。两条腿同科目意味着
--    净额恒为 0，分录写了等于没写，余额视图 `user_wallet_balance` 也算不出变化。
--  · 其余六个（asset:crypto:tron:pool / equity:fx_clearing:USDT / equity:fx_clearing:CNY /
--    expense:chain_fee / expense:payment_shortfall / revenue:fx_buffer / liability:deferred_revenue）
--    都是收款链路上的**具体位置**，且前四个的币种是 USDT/TRX —— 连币种都对不上（见下）。
--
-- ------------------------------------------------------------
-- kind = 'expense' 与 currency = 'CNY' 的理由
-- ------------------------------------------------------------
--
-- **kind='expense'**：管理员凭空给用户加钱，对公司就是一笔真实支出 ——
-- 我们承担了这段服务的成本却没有对应的收入。记成 expense 意味着它出现在损益表上，
-- 意味着月底有人会问「这一格这个月为什么是 3000 元」。**那正是想要的效果**：
-- D10 在 page-inventory §D10 里的定性是「等于印钱」，一个等于印钱的按钮必须在某处留下数字。
-- 记成 equity 或 asset 都会让它从损益表上消失 —— 那时它就只剩审计日志一条线索，
-- 而审计日志是「按人按次翻」的，不是「一眼看出总量异常」的。
--
-- ⚠️ 一个必须知道的不对称：负向调整（扣钱、冲正一次误加）会让这个科目出现**负的费用**
--    （贷方余额）。这是刻意的，**不要因此拆成 adjust_in / adjust_out 两个科目**：
--    拆开之后「加错了又改回来」会变成两笔真实业务，净额为零这个事实反而看不见了。
--
-- **currency='CNY'**：余额全程以人民币分计价（wallet_balances 与 liability:user_wallet 都是 CNY）。
-- 两条腿必须同币种，否则按 `(entry_id, currency)` 分组之后各自不平 ——
-- 那正是 ADR 0012 §17.6(a) 修订不变量要防的形态，且 §17.6(d) 断言 2 每天都会报红。
-- 🔴 顺带钉住 ADR 0012 §23 最后一条登记的隐患：「一旦有任何 USDT 计价的分录进入
--    liability:user_wallet，那条每日比对会永久报红」。D10 是最可能第一个踩它的路径
--    （代付人手里是 U），**本行把这条路径钉死在 CNY 上**：要收 USDT 就必须先过一次
--    汇率换算（fx_clearing 那对科目已经在），而不是让 USDT 直接落进用户钱包。

-- 幂等：`ledger_accounts.code` 上有 UNIQUE（0007:16），重放走 DO NOTHING。
-- 🔴 幂等是硬要求而不是礼貌，理由与 0018 逐字相同：目前 migration 是**裸 psql 灌文件、
--    没有版本表、不防重复执行**（deploy.yml「执行数据库迁移」那一步自己登记着这条 TODO）。
--    在那种执行模型下，一支重放会炸的 seed 迁移会把「多跑了一次」变成一次需要人工介入的部署失败。
INSERT INTO ledger_accounts (code, kind, currency) VALUES
  ('expense:admin_adjust', 'expense', 'CNY')
ON CONFLICT (code) DO NOTHING;


-- ============================================================
-- ② admin_users_email_uk → 部分索引（WHERE disabled_at IS NULL）
-- ============================================================
--
-- ------------------------------------------------------------
-- 现象：管理员「删除」是软停用，但邮箱唯一性不认软停用
-- ------------------------------------------------------------
--
-- `deleteAdmin`（D16）写的是 `disabled_at`，不是 `DELETE`（三条理由见 admin_accounts.sql §2.4，
-- 第一条是决定性的：audit_logs.admin_user_id 是 ON DELETE SET NULL，硬删会让他做过的
-- 每一条 D1–D16 记录变成认不出人的孤儿）。软停用是对的。
--
-- 但 `admin_users_email_uk`（0002:73）是**全表**唯一索引，它不认 disabled_at。
-- 于是停用之后那个邮箱**永久占住**：同一个人离职再入职、或者手滑停用了想撤回，
-- `CreateAdminAccount` 都撞 23505 → 409。而 API 上**没有 undelete 端点**（冻结的 openapi 也没给），
-- 现场唯一的「解法」是直接连库改一行 —— 而直接改库正是权限系统存在的意义被绕过的那一刻。
--
-- ------------------------------------------------------------
-- 先例就在隔壁表上，只差这一句
-- ------------------------------------------------------------
--
-- `users_email_uk`（0003:61）本来就是 `WHERE deleted_at IS NULL` 的部分索引，
-- 而且 `GetUserByEmail`（users.sql:16）的 WHERE 与它逐字同形。两张表、同一个软删语义、
-- 同一种唯一性需求，**只有一张写了软删条件**。
--
-- ⚠️ 记一条推论，供下一次建带软删列的表的人用：
--    **软删表上的每一条唯一索引都必须带上软删条件，否则「删除」在唯一性这个维度上不生效** ——
--    而这件事不会以报错的形式出现，只会以「几个月后有个人进不来」的形式出现。
--
-- ------------------------------------------------------------
-- 🔴 这一句改的是语义，不只是索引：读侧必须跟着改（本轮范围外，必须转达）
-- ------------------------------------------------------------
--
-- 改成部分索引之后，**同一个邮箱可以同时存在一条 disabled 行和一条在职行**（这正是目的）。
-- 于是任何「按 email 查管理员」的语句都从「最多一行」变成「可能多行」。
--
-- 实查一处**会因此出问题**的读侧，不在本文件能改的范围内，逐字记在这里：
--    `api/internal/middleware/admin.go:1033` 的 `LookupAdminByIAPEmail` 是
--    `SELECT … FROM admin_users WHERE lower(email) = lower($1)` + `QueryRow` ——
--    **没有 `disabled_at IS NULL`**，而 QueryRow 会静默丢弃多出来的行。
--    没有 ORDER BY 也没有可用索引（部分索引覆盖不了这条不带条件的查询），
--    返回哪一行由物理顺序决定，也就是**先插入的那条 —— 停用的旧行**。
--    随后 checkAdminUsable 看到 Disabled 就 403。
--    实测（本迁移灌完的库，同邮箱两行 id=1 停用 / id=2 在职）：那条 SQL 返回 2 行，
--    **第一行是 id=1 那条停用行** —— 也就是说 QueryRow 拿到的恰好是错的那一条，不是偶尔错。
--    净效果：**本迁移想要放行的「离职再入职」，在登录路径上会变成一个稳定的 403。**
--    修法是那条查询补上 `AND disabled_at IS NULL`（与 users.sql:16 同形）。
--    ⚠️ 在补上之前，重复邮箱只能靠「不要重用邮箱」这条纪律避免 —— 而那等于本迁移没生效。
--
-- ------------------------------------------------------------
-- 为什么 DROP + CREATE 包在一个显式事务里（本仓库第一支这么写的迁移）
-- ------------------------------------------------------------
--
-- 执行模型是裸 psql 灌文件（deploy.yml 自己登记的），也就是**每句各自 autocommit**。
-- 两句分开提交有两个后果，第二个是决定性的：
--   1. 中间存在一个**没有任何唯一约束**的窗口（虽然管理员写入极稀少）；
--   2. 🔴 CREATE 一旦失败，DROP 已经提交 —— 库里从此**没有管理员邮箱唯一索引**，
--      而没有版本表意味着没有任何东西会说出「这支迁移只跑了一半」。
-- 包进事务之后：DROP INDEX 拿到的 ACCESS EXCLUSIVE 锁一直持到 COMMIT，窗口消失；
-- 失败则整体回滚，库里留下的是**改之前那条完整索引**，而不是什么都没有。
--
-- 不用 CONCURRENTLY 的理由也在这里：CONCURRENTLY 不能在事务块里跑，
-- 而 admin_users 是个位数行的表 —— 事务的价值远大于并发建索引的价值。
--
-- ℹ️ up 方向**不会**因为现存数据失败：新索引的条件比旧索引**宽**（旧的约束全部行，
--    新的只约束在职行），旧索引已经禁止了任何重复。这是「加约束难、放约束易」的好的那一半；
--    坏的那一半在 down 里，见 0019_ledger_admin_adjust.down.sql。
BEGIN;
DROP INDEX admin_users_email_uk;
CREATE UNIQUE INDEX admin_users_email_uk ON admin_users (lower(email)) WHERE disabled_at IS NULL;
COMMIT;
